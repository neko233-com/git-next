// The interface languages are data, not code. Every file in `locales/` is one
// language, and the build discovers them on its own, so adding a language means
// dropping in a locale file and rebuilding - no Rust change, no registry edit,
// and no list of supported languages that can drift out of date.
//
// The generated module exposes the raw locale documents. The runtime parses them
// once, on first use, and keeps the result in a process-wide cache.
use std::{env, fs, path::PathBuf};

/// The name of the generated module, included by `src/language/mod.rs`.
const GENERATED: &str = "locales_generated.rs";

fn main() {
    let root = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let locales = root.join("locales");
    println!("cargo:rerun-if-changed=locales");
    println!("cargo:rerun-if-changed=build.rs");

    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));

    let mut entries: Vec<(String, PathBuf)> = Vec::new();
    if locales.is_dir() {
        for entry in fs::read_dir(&locales).expect("locales directory") {
            let path = entry.expect("locale entry").path();
            if path.extension().and_then(|value| value.to_str()) != Some("json") {
                continue;
            }
            let code = path
                .file_stem()
                .and_then(|value| value.to_str())
                .expect("locale file name")
                .to_owned();
            entries.push((code, path));
        }
    }
    // The order is fixed so the language list and the fallback chain are stable
    // across machines, regardless of how the file system enumerates the directory.
    entries.sort_by(|left, right| left.0.cmp(&right.0));

    let mut generated = String::new();
    generated.push_str("// Generated by build.rs. Do not edit.\n");
    generated.push_str("/// The locale documents shipped with this build, keyed by locale code.\n");
    generated.push_str("pub static CATALOGS: &[(&str, &str)] = &[\n");
    for (code, path) in &entries {
        // The document is copied next to the generated file so the include stays
        // relative and the path never depends on the build machine's layout.
        let file_name = format!("{code}.json");
        fs::copy(path, out_dir.join(&file_name)).expect("copy locale document");
        generated.push_str(&format!(
            "    ({:?}, include_str!({:?})),\n",
            code, file_name
        ));
    }
    generated.push_str("];\n");

    fs::write(out_dir.join(GENERATED), generated).expect("write generated locales");
}
